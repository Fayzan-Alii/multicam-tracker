"""Writers for tiny on-disk datasets in the real formats, used by the loader tests."""

from __future__ import annotations

import json
from pathlib import Path

import cv2
import numpy as np

from multicam_tracker.geometry.camera import Camera, look_at


def write_mot17(root: Path, name="MOT17-09", detector="FRCNN", n_frames=4, size=(48, 64), gt_rows=(), det_rows=()):
    seq = root / "train" / f"{name}-{detector}"
    (seq / "img1").mkdir(parents=True)
    (seq / "gt").mkdir()
    (seq / "det").mkdir()
    (seq / "seqinfo.ini").write_text(
        f"[Sequence]\nname={name}-{detector}\nimDir=img1\nframeRate=30\nseqLength={n_frames}\n"
        f"imWidth={size[1]}\nimHeight={size[0]}\nimExt=.jpg\n"
    )
    for f in range(1, n_frames + 1):
        cv2.imwrite(str(seq / "img1" / f"{f:06d}.jpg"), np.full((*size, 3), 10 * f, np.uint8))
    (seq / "gt" / "gt.txt").write_text("".join(",".join(map(str, r)) + "\n" for r in gt_rows))
    (seq / "det" / "det.txt").write_text("".join(",".join(map(str, r)) + "\n" for r in det_rows))
    return seq


def person_box(cam: Camera, xy, height=1.8):
    foot = cam.ground_to_image(np.array([xy]))[0]
    head, _ = cam.project(np.array([[xy[0], xy[1], height]]))
    h = foot[1] - head[0, 1]
    return [foot[0] - 0.2 * h, head[0, 1], foot[0] + 0.2 * h, foot[1]]


def opencv_matrix(name, m):
    m = np.atleast_2d(m)
    data = " ".join(f"{v:.10f}" for v in m.ravel())
    return (f"<{name} type_id=\"opencv-matrix\"><rows>{m.shape[0]}</rows><cols>{m.shape[1]}</cols>"
            f"<dt>d</dt><data>{data}</data></{name}>")


def write_multiview(root: Path, kind: str, people: dict, n_frames_with_images=None, image_size=(40, 60),
                    foot_bias_m: float = 0.0):
    """Write a fake WILDTRACK / MultiviewX tree with two calibrated cameras.

    people: frame_id -> list of (person_id, position_id). GT boxes are generated by projecting
    the true ground position, so a correct loader reprojects them with zero error. With
    foot_bias_m > 0 each box bottom is instead the projection of a point that much closer to the
    camera, as with real boxes whose bottom edge is the nearest foot."""
    from multicam_tracker.data.multiview import SPECS

    spec = SPECS[kind]
    centers = [np.array([3.0, -15.0, 6.0]), np.array([10.0, 30.0, 7.0])] if kind == "wildtrack" else \
              [np.array([-5.0, 8.0, 6.0]), np.array([30.0, 8.0, 6.0])]
    target = np.array([3.0, 9.0, 0.0]) if kind == "wildtrack" else np.array([12.5, 8.0, 0.0])
    K = np.array([[1000.0, 0.0, 960.0], [0.0, 1000.0, 540.0], [0.0, 0.0, 1.0]])
    cams = []
    (root / "calibrations" / spec.intrinsic_dir).mkdir(parents=True)
    (root / "calibrations" / "extrinsic").mkdir(parents=True)
    for i, c in enumerate(centers):
        R = look_at(c, target)
        cam = Camera(K=K, R=R, t=-R @ c, image_size=spec.image_size)
        cams.append(cam)
        rvec, _ = cv2.Rodrigues(R)
        t_file = cam.t / spec.length_to_m
        (root / "calibrations" / spec.intrinsic_dir / spec.intrinsic_files[i]).write_text(
            "<?xml version=\"1.0\"?>\n<opencv_storage>" + opencv_matrix("camera_matrix", K)
            + opencv_matrix("distortion_coefficients", np.zeros((1, 5))) + "</opencv_storage>\n"
        )
        if kind == "wildtrack":  # plain text vectors
            body = (f"<rvec>{' '.join(f'{v:.10f}' for v in rvec.ravel())}</rvec>"
                    f"<tvec>{' '.join(f'{v:.10f}' for v in t_file)}</tvec>")
        else:  # OpenCV matrix nodes
            body = opencv_matrix("rvec", rvec.reshape(1, 3)) + opencv_matrix("tvec", t_file.reshape(1, 3))
        (root / "calibrations" / "extrinsic" / spec.extrinsic_files[i]).write_text(
            "<?xml version=\"1.0\"?>\n<opencv_storage>" + body + "</opencv_storage>\n"
        )
    (root / "annotations_positions").mkdir()
    for frame, persons in people.items():
        entries = []
        for pid, pos in persons:
            xy = spec.position_to_world(pos)
            views = []
            for v, cam in enumerate(cams):
                toward = cam.center[:2] - xy
                box = person_box(cam, xy + foot_bias_m * toward / np.linalg.norm(toward))
                if pid == 99 and v == 1:  # person 99 is invisible in camera 1
                    box = [-1, -1, -1, -1]
                views.append({"viewNum": v, "xmin": box[0], "ymin": box[1], "xmax": box[2], "ymax": box[3]})
            entries.append({"personID": pid, "positionID": pos, "views": views})
        (root / "annotations_positions" / f"{frame:08d}.json").write_text(json.dumps(entries))
    frames = sorted(people) if n_frames_with_images is None else sorted(people)[:n_frames_with_images]
    for v in range(len(cams)):
        d = root / "Image_subsets" / f"C{v + 1}"
        d.mkdir(parents=True)
        for f in frames:
            cv2.imwrite(str(d / f"{f:08d}.png"), np.full((*image_size, 3), v * 50, np.uint8))
    return cams


def write_market(root: Path, files: dict):
    """files: subdir -> list of file names."""
    for sub, names in files.items():
        (root / sub).mkdir(parents=True, exist_ok=True)
        for n in names:
            cv2.imwrite(str(root / sub / n), np.zeros((16, 8, 3), np.uint8))
